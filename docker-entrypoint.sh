#!/bin/sh
set -e

# إن كانت قاعدة البيانات فارغة (أول تشغيل على هذا الخادم)، عبِّئها ببيانات تجريبية
# قابلة للحذف لاحقاً من قبل مسؤول النظام. السكربت نفسه يتجاهل نفسه إن وُجدت بيانات مسبقاً.
if [ ! -f /app/data/app.db ]; then
  echo "لا توجد قاعدة بيانات — تعبئة بيانات أولية..."
  npx tsx src/lib/db/seed.ts || echo "تحذير: فشلت التعبئة الأولية، تابع بدون بيانات تجريبية."
fi

exec npm run start
